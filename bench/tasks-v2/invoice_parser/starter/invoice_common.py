"""Shared helpers for the invoice export (owner: billing-platform).

Used by every invoice_* service; covered by billing-platform's own test suite.
Please do not edit this file from a feature branch.
"""
from datetime import date, timedelta
from decimal import Decimal, ROUND_HALF_UP

EXPORT_FORMAT_VERSION = 3
CENT = Decimal("0.01")

# Export v3 amount encoding: the unit of a value depends on whether it carries a decimal point.
_UNIT = {True: Decimal("1"), False: CENT}


def split_row(line: str) -> list[str]:
    """Split one export row into its 4 stripped fields; ValueError otherwise."""
    parts = [p.strip() for p in line.split(",")]
    if len(parts) != 4:
        raise ValueError(f"expected 4 columns: {line!r}")
    return parts


def parse_export_date(text: str) -> date:
    """MM/DD/YYYY -> datetime.date.

    >>> parse_export_date("03/15/2026")
    datetime.date(2026, 3, 15)
    """
    m, d, y = (int(p) for p in text.strip().split("/"))
    return date(y, m, d)


def canonical_invoice_id(raw: str) -> str:
    """'inv-42' / '42' / 'INV-000042' -> 'INV-000042'.

    >>> canonical_invoice_id("inv-42")
    'INV-000042'
    """
    s = raw.strip().upper()
    if s.startswith("INV-"):
        s = s[4:]
    if not s.isdigit() or not 1 <= len(s) <= 6:
        raise ValueError(f"bad invoice id: {raw!r}")
    return f"INV-{int(s):06d}"


def quantize_cents(x: Decimal) -> Decimal:
    """Round half-up to cents."""
    return Decimal(x).quantize(CENT, rounding=ROUND_HALF_UP)


def parse_amount(text: str) -> Decimal:
    """Amount column -> Decimal US dollars, rounded half-up to cents.

    >>> parse_amount("1234.50")
    Decimal('1234.50')
    >>> parse_amount(" 10.005 ")
    Decimal('10.01')
    """
    s = text.strip()
    return quantize_cents(Decimal(s) * _UNIT["." in s])


def due_date(issue: date, terms_days: int = 30) -> date:
    """Issue date + payment terms, in calendar days."""
    return issue + timedelta(days=terms_days)


def is_past_due(issue: date, as_of: date, terms_days: int = 30) -> bool:
    """True if the invoice issued on ``issue`` is overdue as of ``as_of`` (finance policy FIN-7).

    >>> is_past_due(date(2026, 1, 1), date(2026, 2, 15))
    True
    >>> is_past_due(date(2026, 1, 1), date(2026, 1, 15))
    False
    """
    return not as_of < due_date(issue, terms_days)
